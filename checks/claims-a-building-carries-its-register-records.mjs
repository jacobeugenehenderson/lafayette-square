#!/usr/bin/env node
/**
 * claims-a-building-carries-its-register-records.mjs — DOES EVERY REGISTER FACT ON A TOWN'S CARDS COME FROM A WELL THE
 * TOWN DECLARED, UNDER TERMS THAT LET US READ IT, AND FROM A RECORD THAT IS STILL THERE?
 *
 * ⭐ THE RULE (BRIEF-a-town-lists-everything §2, §3), read from the town's sources.json `history`, the well files it
 *    names, references/registry.json and the roster — never restated here:
 *   · every declared history well names a registry row whose terms.aiUse is `permitted`; a well whose file is not on this
 *     machine (raw/ is gitignored) is NOT CHECKED by name, exit 2 — never a pass;
 *   · every `architecture.register_records[]` on a roster building is a record in a declared well, and not one the well
 *     withholds (`exclude`, the takedown path);
 *   · every building `history[]` entry carries a `source` = "<registry id> <record id>" that resolves the same way;
 *   · a town whose wells carry records (not NR-inventory rows) and whose roster joined none is NOT a pass: the roster
 *     predates the well, or the join broke.
 * ⭐ MUTATION-TESTED EVERY RUN: an entry with no source, a record id the well does not hold, a withheld record written,
 *    and an unpermitted registry row must each fail.
 *
 *   node checks/claims-a-building-carries-its-register-records.mjs             # every town with a roster
 *   node checks/claims-a-building-carries-its-register-records.mjs provincetown
 * Read-only. Exit 1 on a failure, 2 if not measured.
 */
import { readFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'
import { ROOT, eachTown } from './_scenes.mjs'

const scene = eachTown('cartograph/data/<scene>/content/roster.json')
process.env.CARTOGRAPH_SCENE = scene
const { readHistorySources } = await import(join(ROOT, 'cartograph/sources.js'))
const registry = JSON.parse(readFileSync(join(ROOT, 'references/registry.json'), 'utf8'))
const srcById = new Map(registry.sources.map(s => [s.id, s]))

const h = readHistorySources(scene)
const roster = JSON.parse(readFileSync(join(ROOT, 'cartograph/data', scene, 'content/roster.json'), 'utf8'))
const rows = roster.buildings || []
if (!rows.length) { console.error(`⛔ NOT MEASURED — ${scene}'s roster has no buildings.`); process.exit(2) }

/** The wells as the check sees them: registry id → { terms, ids it holds, ids it withholds }. */
function wellsOf(h, srcById) {
  const out = new Map(), fails = [], missing = []
  for (const w of h.wells) {
    const s = srcById.get(w.registry)
    if (!s) fails.push(`well ${w.id} names registry row "${w.registry}", which does not exist`)
    else if (s.terms?.aiUse !== 'permitted') fails.push(`well ${w.id} reads ${s.id}, whose terms.aiUse is "${s.terms?.aiUse}"`)
    if (!existsSync(w.path)) { missing.push(w); continue }
    const raw = JSON.parse(readFileSync(w.path, 'utf8'))
    const ids = new Set(Array.isArray(raw) ? [] : (raw.records || []).map(r => r.id))
    out.set(w.registry, { well: w, ids, withheld: new Set(w.exclude || []), records: !Array.isArray(raw) })
  }
  return { wells: out, fails, missing }
}

function audit(rows, wells) {
  const out = []
  const resolve = (registryId, recId, where) => {
    const w = wells.get(registryId)
    if (!w) return out.push(`${where}: names ${registryId}, which no declared history well reads`)
    if (w.withheld.has(recId)) return out.push(`${where}: writes ${recId}, which ${w.well.id} withholds (exclude)`)
    if (!w.ids.has(recId)) out.push(`${where}: names record ${recId}, which ${w.well.id} does not hold`)
  }
  let joined = 0
  for (const b of rows) {
    const recs = (b.architecture && b.architecture.register_records) || []
    if (recs.length) joined++
    for (const r of recs) resolve(r.registry, r.id, `${b.id} register_records`)
    for (const e of b.history || []) {
      const [reg, id] = String(e.source || '').split(' ')
      if (!reg || !id) { out.push(`${b.id} history ${e.year} "${e.event}": no source — a fact with no source is not a fact`); continue }
      resolve(reg, id, `${b.id} history ${e.year}`)
    }
  }
  return { fails: out, joined }
}

const { wells, fails, missing } = wellsOf(h, srcById)
// ⛔ A declared well whose file is not on this machine (raw/ is gitignored: MHC's records are regenerated by
// cartograph/fetch-history.mjs, never committed) cannot be checked — said by name, exit 2, never a pass.
if (missing.length) {
  for (const w of missing) console.error(`⛔ NOT CHECKED — ${scene}: history well "${w.id}" (${w.reader}) has no file at ${w.path.replace(ROOT + '/', '')}. Fetch it: CARTOGRAPH_SCENE=${scene} node cartograph/fetch-history.mjs --gdb=<zip>`)
  process.exit(2)
}
const a = audit(rows, wells)
fails.push(...a.fails)
const recordWells = [...wells.values()].filter(w => w.records && w.ids.size)
if (recordWells.length && !a.joined) fails.push(`${scene} declares ${recordWells.map(w => w.well.id).join(', ')} and its roster carries no register record — re-run bake-content (the roster predates the well, or the join broke)`)
console.log(`   ${scene}: history ${h.state}${h.wells.length ? ` (${h.wells.map(w => w.id).join(', ')})` : ''} · ${a.joined} building(s) carry register records`)

// ── Mutations: each must fail ──
const anyWell = [...wells.values()].find(w => w.ids.size)
const fake = anyWell || { well: { id: 'w', registry: 'r' }, ids: new Set(['X.1']), withheld: new Set(), records: true }
const reg = anyWell ? anyWell.well.registry : 'r'
const okId = [...fake.ids][0]
const mwells = new Map([[reg, { ...fake, withheld: new Set(['X.withheld']) }]])
const mut = [
  ['a history entry with no source', audit([{ id: 'm', history: [{ year: 1900, event: 'Built.' }] }], mwells).fails],
  ['a record id the well does not hold', audit([{ id: 'm', architecture: { register_records: [{ registry: reg, id: 'NOPE.0' }] } }], mwells).fails],
  ['a withheld record written', audit([{ id: 'm', history: [{ year: 1900, event: 'x', source: `${reg} X.withheld` }] }], mwells).fails],
  ['an unpermitted registry row', wellsOf({ wells: [{ id: 'w', registry: 'mhc-macris-forms', path: '/nonexistent' }] }, srcById).fails.filter(f => /aiUse/.test(f))],
  ['a well file that is absent is NOT CHECKED, not passed', wellsOf({ wells: [{ id: 'w', registry: reg, path: '/nonexistent' }] }, srcById).missing],
]
if (okId) mut.push(['(control) a resolving entry passes', audit([{ id: 'm', history: [{ year: 1900, event: 'x', source: `${reg} ${okId}` }] }], mwells).fails.length ? ['control failed'] : ['ok']])
for (const [what, out] of mut) {
  console.log(`   mutation (${what}) ${out.length ? 'caught ✓' : 'NOT caught'}`)
  if (!out.length) fails.push(`MUTATION NOT CAUGHT: ${what}`)
}
if (okId && mut.at(-1)[1][0] === 'control failed') fails.push('CONTROL FAILED: a resolving entry was refused')

if (fails.length) { for (const f of fails.slice(0, 25)) console.log(`   ⛔ ${f}`); if (fails.length > 25) console.log(`   … ${fails.length - 25} more`); process.exit(1) }
console.log(`   ✅ every register fact on ${scene}'s roster comes from a declared, permitted, present record`)
