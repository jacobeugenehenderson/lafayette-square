#!/usr/bin/env node
/**
 * hydrate-anchor-cards.js — one-shot build-time hydration of the four
 * seasonal anchor cards from cartograph/proceduralSky.js.
 *
 * For each season's reference date × 24 clock hours at the instance's
 * lat/lon, samples SunCalc.getPosition() → proceduralSkyAt(altitude,
 * isDawn) → a { horizon, low, mid, high, sunGlow } hex tuple. Emits a
 * 4 × 24 × 5 hex table to stdout as a JS module fragment suitable for
 * pasting (or piping) into src/cartograph/skyGrid.js as the
 * ANCHOR_CARDS_PROCEDURAL constant.
 *
 * Usage:
 *   node cartograph/pipeline/hydrate-anchor-cards.js > /tmp/cards.js
 *
 * Re-runnable any time the keyframes in proceduralSky.js are tuned.
 * Wren's artistic deviation pass (Phase B of the sky-pivot brief)
 * happens AFTER this hydration: edit ANCHOR_CARDS_ARTISTIC in
 * skyGrid.js to deviate winter / spring / autumn per the painter's eye.
 *
 * See meteorologist/NOTES.md 2026-05-20 "Sky architecture pivot" ADR.
 */
import SunCalc from 'suncalc'
import { proceduralSkyAt, SEASON_TRANSFORMS } from '../proceduralSky.js'

// Match src/instance.js — keeping this script self-contained so it can
// run pre-bundle. Update both if a different instance is ever added.
const LAT = 38.6160
const LON = -90.2161
const TIMEZONE_OFFSET_HOURS = -6  // CST (America/Chicago, ignoring DST for cardinal-day reference)

// Cardinal year-anchor reference dates. Year is arbitrary; SunCalc only
// needs date+time for altitude computation, and the four solstice/equinox
// dates differ negligibly across years for sky-color purposes.
const REF_DATES = {
  winter: { year: 2026, month: 11, day: 21 },  // Dec 21 — solstice
  spring: { year: 2026, month:  2, day: 20 },  // Mar 20 — equinox
  summer: { year: 2026, month:  5, day: 21 },  // Jun 21 — solstice
  autumn: { year: 2026, month:  8, day: 22 },  // Sep 22 — equinox
}

function hourClock(refDate, hour) {
  // Build a Date at hour h on the reference date in local time. Using
  // UTC with timezone offset so this runs the same on any host TZ.
  return new Date(Date.UTC(
    refDate.year, refDate.month, refDate.day,
    hour - TIMEZONE_OFFSET_HOURS, 0, 0,
  ))
}

function buildCard(season) {
  const ref = REF_DATES[season]
  const transform = SEASON_TRANSFORMS[season]
  // Solar-noon test: SunCalc gives the local-noon hour for the date.
  const times = SunCalc.getTimes(hourClock(ref, 12), LAT, LON)
  const solarNoonLocalH = times.solarNoon.getUTCHours() + TIMEZONE_OFFSET_HOURS + times.solarNoon.getUTCMinutes() / 60
  const card = []
  for (let h = 0; h < 24; h++) {
    const clock = hourClock(ref, h)
    const sunPos = SunCalc.getPosition(clock, LAT, LON)
    const isDawn = h < solarNoonLocalH
    card.push(proceduralSkyAt(sunPos.altitude, isDawn, transform))
  }
  return card
}

const seasons = ['winter', 'spring', 'summer', 'autumn']
const cards = {}
for (const s of seasons) cards[s] = buildCard(s)

// Emit as a JS module fragment so the operator can copy-paste into
// skyGrid.js (or pipe into a generated file).
console.log('// Auto-generated by cartograph/pipeline/hydrate-anchor-cards.js')
console.log('// Re-run any time proceduralSky.js KEYFRAMES are tuned.')
console.log('// Format: 4 anchors × 24 hours × 5 bands of hex strings.')
console.log('')
console.log('export const ANCHOR_CARDS_PROCEDURAL = {')
for (const s of seasons) {
  console.log(`  ${s}: [`)
  for (let h = 0; h < 24; h++) {
    const c = cards[s][h]
    const hStr = String(h).padStart(2, '0')
    console.log(`    { horizon: '${c.horizon}', low: '${c.low}', mid: '${c.mid}', high: '${c.high}', sunGlow: '${c.sunGlow}' },  // ${hStr}:00`)
  }
  console.log(`  ],`)
}
console.log('}')
